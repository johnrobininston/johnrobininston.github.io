#!/usr/bin/env python3
"""Audit topics/*.qmd and write _topics-audit.md.

Run from anywhere:  python3 _tools/topics_audit.py
Read-only on the notes; only (re)writes _topics-audit.md.

Terms
- hub:      a note linked from topics/topics.qmd that exists
- sub-index: a note tagged `hub` and listed under a hub; notes it links to
            count as listed under that hub
- listed:   a note linked from at least one hub
- stub:     a note with almost no prose (< STUB_CHARS non-space characters)
- thin:     one section or little prose (< THIN_CHARS), but not a stub
"""
import collections
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOPICS = os.path.join(ROOT, "topics")
OUT = os.path.join(ROOT, "_topics-audit.md")
STUB_CHARS, THIN_CHARS = 200, 800
LINK = re.compile(r"\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]")
MALFORMED = re.compile(r"^(knowledge-|files-|memory-)|-pdf$|-notes-")


def clean(text):
    text = re.sub(r"```.*?```", "", text, flags=re.S)
    return re.sub(r"<!--.*?-->", "", text, flags=re.S)


def read(name):
    with open(os.path.join(TOPICS, name + ".qmd")) as f:
        return f.read()


names = sorted(os.path.basename(p)[:-4] for p in glob.glob(TOPICS + "/*.qmd"))
exists = set(names)
lower = {n.lower(): n for n in names}
out_links = {n: [l.strip() for l in LINK.findall(clean(read(n)))] for n in names}
in_links = collections.defaultdict(set)
for n, ls in out_links.items():
    for l in ls:
        if l != n:
            in_links[l].add(n)

hubs = []
for l in out_links["topics"]:
    if l in exists and l not in hubs:
        hubs.append(l)
# Sub-indexes: notes tagged `hub` that are listed under a hub. They count as
# hubs one level down, so notes they list are credited to the parent hub.
HUB_TAG = re.compile(r"(?m)^tags:.*\bhub\b")
listed = collections.defaultdict(set)
for h in hubs:
    for l in out_links[h]:
        listed[l].add(h)
sub_hubs = [n for n in names if n not in hubs and n in listed
            and HUB_TAG.search(read(n))]
for s in sub_hubs:
    for l in out_links[s]:
        listed[l] |= listed[s]


# ---- step 1: unlisted notes, with a suggested parent hub
def suggest(n):
    score = collections.Counter()
    for m in set(out_links[n]) | in_links[n]:
        for h in listed.get(m, ()):
            score[h] += 1
    return score.most_common(1)[0][0] if score else None


unlisted = [n for n in names if n not in listed and n not in hubs and n != "topics"]
by_parent = collections.defaultdict(list)
for n in unlisted:
    by_parent[suggest(n)].append(n)

# ---- step 2: links to notes that do not exist
missing = collections.defaultdict(set)
for n, ls in out_links.items():
    for l in ls:
        if l not in exists:
            missing[l].add(n)
case = {m: lower[m.lower()] for m in missing if m.lower() in lower}
malformed = [m for m in missing if MALFORMED.search(m) and m not in case]
genuine = [m for m in missing if m not in case and m not in malformed]

# ---- step 3: unfinished notes
info = {}
for n in names:
    t = re.sub(r"^---\n.*?\n---\n", "", clean(read(n)), count=1, flags=re.S)
    lines = t.split("\n")
    heads = [i for i, l in enumerate(lines) if re.match(r"#{1,6} ", l)]
    empty = []
    for k, i in enumerate(heads):
        end = heads[k + 1] if k + 1 < len(heads) else len(lines)
        if not "".join(lines[i + 1:end]).strip():
            empty.append(lines[i].lstrip("# ").strip())
    prose = re.sub(r"\s+", "", re.sub(r"(?m)^#{1,6} .*$", "", t))
    info[n] = dict(chars=len(prose), heads=len(heads), empty=empty,
                   inb=len(in_links[n]), wip="WIP" in t[:600])
stubs = [n for n in names if info[n]["chars"] < STUB_CHARS]
thin = [n for n in names if n not in stubs and (
    info[n]["chars"] < THIN_CHARS or (info[n]["heads"] <= 1 and info[n]["chars"] < 1500))]
has_empty = [n for n in names if info[n]["empty"] and n not in stubs]


def nl(n):
    return f"[[{n}]]"


def wrap(prefix, items, width=79):
    """Comma-separated items wrapped under a list bullet."""
    lines, cur = [], prefix
    for i, it in enumerate(items):
        piece = it + ("," if i < len(items) - 1 else "")
        if len(cur) + len(piece) + 1 > width and cur.strip():
            lines.append(cur.rstrip())
            cur = "  "
        cur += piece + " "
    lines.append(cur.rstrip())
    return lines


o = ["---", "title: Topics audit", "---", ""]
o += ["Generated by `_tools/topics_audit.py`. Do not edit the lists by hand;",
      "re-run the script. Notes are tracked in the **Decisions / notes**",
      "section at the end, which the script preserves.", ""]
o += ["## Summary", "",
      f"- Notes: {len(names)}; hubs: {len(hubs)} ({', '.join(hubs)})",
      f"- Sub-indexes (tag `hub`): {', '.join(sub_hubs) or 'none'}",
      f"- Not listed in any hub: {len(unlisted)}",
      f"- Links to missing notes: {len(missing)} targets "
      f"({len(genuine)} genuine, {len(malformed)} malformed, "
      f"{len(case)} case mismatch)",
      f"- Stubs: {len(stubs)}; thin: {len(thin)}; "
      f"with empty sections: {len(has_empty)}", ""]

o += ["## 1. Notes not listed in a parent topic", "",
      "Suggested parent = the hub whose listed notes this note links to or is",
      "linked from most. `None` means no connection to any hub.", ""]
for p in sorted(by_parent, key=lambda x: (x is None, x or "")):
    o += [f"### {p or 'None'} ({len(by_parent[p])})", ""]
    o += wrap("- ", [nl(n) for n in by_parent[p]]) + [""]

o += ["## 2. Links to notes that do not exist", ""]
o += ["### Genuine missing notes", "",
      "Sorted by number of notes linking to them.", ""]
for m in sorted(genuine, key=lambda m: (-len(missing[m]), m)):
    src = sorted(missing[m])
    shown = ", ".join(nl(s) for s in src[:4]) + (" ..." if len(src) > 4 else "")
    o += [f"- `{m}` ({len(src)}): {shown}"]
o += ["", "### Malformed links (likely pasted Obsidian paths)", ""]
for m in sorted(malformed):
    o += [f"- `{m}`: " + ", ".join(nl(s) for s in sorted(missing[m]))]
o += ["", "### Case mismatches", ""]
for m in sorted(case):
    o += [f"- `{m}` should be `{case[m]}`: "
          + ", ".join(nl(s) for s in sorted(missing[m]))]

o += ["", "## 3. Unfinished notes", "",
      f"### Stubs (under {STUB_CHARS} characters of prose)", "",
      "Marked `*` if other notes link to them (candidates for step 4).", ""]
o += wrap("- ", [nl(n) + ("*" if info[n]["inb"] else "") for n in stubs]) + [""]
o += [f"### Thin (under {THIN_CHARS} characters, or one section)", ""]
o += wrap("- ", [nl(n) for n in thin]) + [""]
o += ["### Notes with empty sections", ""]
for n in has_empty:
    o += [f"- {nl(n)}: " + ", ".join(info[n]["empty"])]

o += ["", "## 4. Work-in-progress template", "",
      "Template: `_templates/wip-note.qmd`. Stubs with inbound links:", ""]
o += wrap("- ", [nl(n) + f" ({info[n]['inb']})" for n in
                 sorted((n for n in stubs if info[n]["inb"]),
                        key=lambda n: -info[n]["inb"])]) + [""]

notes = "## Decisions / notes\n\n- (none yet)\n"
if os.path.exists(OUT):
    old = open(OUT).read()
    if "## Decisions / notes" in old:
        notes = old[old.index("## Decisions / notes"):]
open(OUT, "w").write("\n".join(o) + "\n" + notes)
print(f"wrote {OUT}")
